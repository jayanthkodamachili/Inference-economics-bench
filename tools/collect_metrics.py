"""Re-measure the deterministic figures, read the recorded ones, write docs/metrics.json.

Accuracy is deterministic: same seed, same corpus, same split, same number. Latency is
not. Mixing the two in one check would mean either re-measuring latency and failing at
random, or recording accuracy and never noticing when it drifts.

So they are split. tools/check_reproducible.py re-fits the cheap models and asserts their
recorded accuracies still hold exactly. Everything timed is read from the recorded run in
docs/experiments, regenerated deliberately by make bench. ADR-003 has the reasoning.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPERIMENT_DIR = ROOT / "docs" / "experiments"
METRICS_PATH = ROOT / "docs" / "metrics.json"

EXPERIMENTS = ("e1_the_frontier", "e2_does_batching_change_the_answer",
               "e3_the_budget_decides", "e4_when_does_it_pay")
CHECKED_DOCUMENTS = ("README.md", "docs/adr/ADR-005-what-this-cannot-measure.md")
TABLE_ANCHOR = ["| {} |"]

ANCHORS: dict[str, list[str]] = {
    "tests_total": ["{} tests"],
    "coverage_line_pct": ["{} percent line coverage"],
    "most_accurate_accuracy": TABLE_ANCHOR,
    "transformer_accuracy": TABLE_ANCHOR,
    "accuracy_points_gained": ["{} accuracy points", "gap is {} points"],
    "cost_multiple": ["{} times the price", "{} times more"],
    "boosting_over_transformer_points": ["by {} accuracy points", "{} points more"],
    "boosting_over_transformer_cost": ["{} times as much per call", "{} times the cost"],
    "boosting_size_mb": ["{} mb artifact", "{} mb model"],
    "transformer_size_kb": ["{} kb", "against {} kb"],
    "premium_at_batch_1": ["{}x at batch 1", "from {}x"],
    "premium_at_largest_batch": ["to {}x at batch 64", "{}x at batch 64"],
    "tie_tolerance": ["resolve better than {}", "within {}"],
    "reversal_count": ["{} pairs reverse", "exactly {} pair"],
    "boosting_batch_saving": ["{} times cheaper", "{}x cheaper when batched"],
    "transformer_batch_saving": ["only {} times", "{}x for the transformer"],
    "distinct_models_by_budget": ["{} different models"],
    "disagreeing_pairs": ["{} of them", "{} select"],
    "total_pairs": ["{} budget and latency pairs", "all {} pairs"],
    "best_value_points_per_dollar": ["{} accuracy points per extra dollar"],
    "worst_value_points_per_dollar": ["down to {}", "is {} points"],
    "value_ratio": ["ratio of {}", "{} between"],
    "bigram_lift_at_zero": ["gains {} accuracy points", "exactly {} points"],
    "bigram_lift_at_max": ["gains {} points", "to {} points"],
    "min_gap_points": ["from {} points", "as little as {}"],
    "max_gap_points": ["to {} points", "as much as {}"],
    "e4_zero_unigram": ["unigram reaches {}", "{} at phrase rate zero"],
    "e4_zero_transformer": ["transformer manages {}", "only {}"],
    "price_usd_per_hour": ["${} an hour", "at ${}"],
}


def run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, check=False, **kwargs)


def measure_suite(skip_tests: bool) -> dict:
    junit, cov = ROOT / "junit.xml", ROOT / "coverage.json"
    if skip_tests:
        missing = [p.name for p in (junit, cov) if not p.exists()]
        if missing:
            raise SystemExit(f"--skip-tests given but {', '.join(missing)} not found")
    else:
        result = run([sys.executable, "-m", "pytest", f"--junitxml={junit}",
                      "--cov=inference_economics", "--cov-report=json", "-q"],
                     capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stdout[-4000:], file=sys.stderr)
            raise SystemExit("test suite failed, refusing to publish metrics")
    suite = ET.parse(junit).getroot()
    node = suite if suite.tag == "testsuite" else suite.find("testsuite")
    totals = json.loads(cov.read_text())["totals"]
    return {"tests_total": int(node.get("tests", 0)) - int(node.get("skipped", 0)),
            "coverage_line_pct": int(totals["percent_covered"])}


def load_experiments() -> dict[str, dict]:
    payloads = {}
    for name in EXPERIMENTS:
        path = EXPERIMENT_DIR / f"{name}.json"
        if not path.exists():
            raise SystemExit(
                f"recorded experiment missing: {path.name}\n"
                "Timings are not regenerated by this script. Run `make bench`."
            )
        payloads[name] = json.loads(path.read_text())
    return payloads


def derive(suite: dict, exp: dict[str, dict]) -> dict:
    e1, e2 = exp["e1_the_frontier"], exp["e2_does_batching_change_the_answer"]
    e3, e4 = exp["e3_the_budget_decides"], exp["e4_when_does_it_pay"]

    points = {p["model"]: p for p in e1["points"]}
    boosting, transformer = points["svd_boosting"], points["transformer"]

    metrics: dict = {
        **suite,
        "price_usd_per_hour": e1["price"]["usd_per_hour"],
        "most_accurate_accuracy": e1["most_accurate_accuracy"],
        "transformer_accuracy": transformer["accuracy"],
        "accuracy_points_gained": e1["accuracy_points_gained"],
        "cost_multiple": e1["cost_multiple"],
        "boosting_over_transformer_points": round(
            (boosting["accuracy"] - transformer["accuracy"]) * 100, 2),
        "boosting_over_transformer_cost": round(
            boosting["usd_per_million"] / transformer["usd_per_million"], 1),
        "boosting_size_mb": round(boosting["size_bytes"] / 1024 / 1024, 0),
        "transformer_size_kb": round(transformer["size_bytes"] / 1024, 0),
        "premium_at_batch_1": e2["premium_at_batch_1"],
        "premium_at_largest_batch": e2["premium_at_largest_batch"],
        "tie_tolerance": e2["tie_tolerance"],
        "reversal_count": e2["reversal_count"],
        "boosting_batch_saving": e2["savings"]["svd_boosting"],
        "transformer_batch_saving": e2["savings"]["transformer"],
        "distinct_models_by_budget": e3["distinct_models_by_budget"],
        "disagreeing_pairs": e3["disagreeing_pairs"],
        "total_pairs": e3["total_pairs"],
        "best_value_points_per_dollar": e3["best_value_step"]["points_per_extra_dollar"],
        "worst_value_points_per_dollar": e3["worst_value_step"]["points_per_extra_dollar"],
        "value_ratio": int(e3["value_ratio"]),
        "bigram_lift_at_zero": e4["bigram_lift_at_zero"],
        "bigram_lift_at_max": e4["bigram_lift_at_max"],
        "min_gap_points": e4["min_gap_points"],
        "max_gap_points": e4["max_gap_points"],
        "e4_zero_unigram": e4["rows"][0]["cheap_accuracy"],
        "e4_zero_transformer": e4["rows"][0]["transformer_accuracy"],
    }

    for name, point in points.items():
        metrics[f"e1_{name}_accuracy"] = point["accuracy"]
        metrics[f"e1_{name}_cost"] = round(point["usd_per_million"], 4)
        metrics[f"e1_{name}_p99"] = round(point["p99_ms"], 3)
        for suffix in ("accuracy", "cost", "p99"):
            ANCHORS.setdefault(f"e1_{name}_{suffix}", TABLE_ANCHOR)

    for cell in e2["cells"]:
        key = f"e2_{cell['model']}_{cell['batch_size']}"
        metrics[key] = round(cell["usd_per_million"], 4)
        ANCHORS.setdefault(key, TABLE_ANCHOR)

    # The swept constants are metrics too. They appear in published tables, so leaving
    # them unregistered would mean the reverse check flags every row of the sweep, and
    # silencing that by hand is how a checker starts getting worked around.
    for budget in e3["budgets"]:
        key = f"e3_budget_label_{str(budget).replace('.', '')}"
        metrics[key] = budget
        ANCHORS.setdefault(key, TABLE_ANCHOR)

    for rate in e4["phrase_rates"]:
        key = f"e4_rate_label_{str(rate).replace('.', '')}"
        metrics[key] = rate
        ANCHORS.setdefault(key, TABLE_ANCHOR)

    for budget, model in e3["by_budget"].items():
        if model:
            metrics[f"e3_budget_{budget.replace('.', '')}"] = model
            ANCHORS.setdefault(f"e3_budget_{budget.replace('.', '')}", TABLE_ANCHOR)

    for upgrade in e3["upgrades"]:
        key = f"e3_step_{upgrade['from']}_{upgrade['to']}"
        metrics[key] = upgrade["points_per_extra_dollar"]
        ANCHORS.setdefault(key, TABLE_ANCHOR)

    for row in e4["rows"]:
        tag = str(row["phrase_rate"]).replace(".", "")
        metrics[f"e4_{tag}_unigram"] = row["cheap_accuracy"]
        metrics[f"e4_{tag}_bigram"] = row["bigram_accuracy"]
        metrics[f"e4_{tag}_transformer"] = row["transformer_accuracy"]
        metrics[f"e4_{tag}_gap"] = row["gap_points"]
        for suffix in ("unigram", "bigram", "transformer", "gap"):
            ANCHORS.setdefault(f"e4_{tag}_{suffix}", TABLE_ANCHOR)

    return metrics


# Formatting is declared per metric rather than inferred from the name. An earlier version
# guessed from suffixes and got several wrong at once: a cost ratio rendered as 33.6000
# because the key ended in _cost, and an accuracy gap of 9.19 rendered as 9.2. A figure
# that renders two ways defeats the anchor mechanism entirely, so the rule is explicit.
SCALAR_FORMATS = {
    "price_usd_per_hour": "{:.5f}",
    "most_accurate_accuracy": "{:.4f}",
    "transformer_accuracy": "{:.4f}",
    "accuracy_points_gained": "{:.2f}",
    "cost_multiple": "{:.1f}",
    "boosting_over_transformer_points": "{:.2f}",
    "boosting_over_transformer_cost": "{:.1f}",
    "boosting_size_mb": "{:.0f}",
    "transformer_size_kb": "{:.0f}",
    "premium_at_batch_1": "{:.1f}",
    "premium_at_largest_batch": "{:.1f}",
    "tie_tolerance": "{:.2f}",
    "boosting_batch_saving": "{:.1f}",
    "transformer_batch_saving": "{:.1f}",
    "best_value_points_per_dollar": "{:.1f}",
    "worst_value_points_per_dollar": "{:.1f}",
    "bigram_lift_at_zero": "{:.2f}",
    "bigram_lift_at_max": "{:.2f}",
    "min_gap_points": "{:.2f}",
    "max_gap_points": "{:.2f}",
    "e4_zero_unigram": "{:.4f}",
    "e4_zero_transformer": "{:.4f}",
}


def display_strings(metrics: dict) -> dict[str, str]:
    out = {}
    for key, value in metrics.items():
        if isinstance(value, str):
            out[key] = value
        elif key in SCALAR_FORMATS:
            out[key] = SCALAR_FORMATS[key].format(value)
        elif isinstance(value, int):
            out[key] = str(value)
        elif key.startswith("e3_step_"):
            # Points per extra dollar, which runs from single digits to thousands. These
            # keys end in a model name, so the accuracy rule below would have claimed them
            # and printed 6975.0000.
            out[key] = f"{value:.1f}"
        elif (key.endswith(("_accuracy", "_bigram", "_unigram", "_transformer", "_cost"))
              or key.startswith("e2_")):
            out[key] = f"{value:.4f}"
        elif key.endswith("_p99"):
            out[key] = f"{value:.3f}"
        elif key.endswith("_gap"):
            out[key] = f"{value:.2f}"
        elif "_budget_label_" in key:
            out[key] = f"{value:g}"
        elif "_rate_label_" in key:
            out[key] = f"{value:.1f}"
        else:
            out[key] = f"{value:.1f}"
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Re-measure the deterministic figures.")
    parser.add_argument("--skip-tests", action="store_true")
    args = parser.parse_args()
    metrics = derive(measure_suite(args.skip_tests), load_experiments())
    METRICS_PATH.write_text(json.dumps({
        "metrics": metrics, "display": display_strings(metrics), "anchors": ANCHORS,
        "checked_documents": list(CHECKED_DOCUMENTS),
        "note": "accuracies are re-measured by tools/check_reproducible.py; timings are "
                "read from the recorded run, because rerunning them changes them",
    }, indent=2) + "\n")
    print(f"wrote {METRICS_PATH} with {len(metrics)} metrics")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
